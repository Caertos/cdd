import React from 'react';
import { render } from '@testing-library/react';
import { CreationSummary } from '../src/components/CreationSummary.jsx';
import { buildCreationSummary } from '../src/helpers/creationSummary.js';

const ESC = '\u001b';
const CSI = `${ESC}[`;
/** The 8-bit heads: the same sequences with a shorter introducer. */
const C1_CSI = '\u009b';
const C1_OSC = '\u009d';

/**
 * The rendered text must carry no control byte at all: not the ESC that
 * starts an escape sequence, not the 8-bit heads (0x9B, 0x9D), not a stray
 * C0 control. Only TAB and LF are allowed — they are the two C0 controls
 * that carry meaning inside a line of text.
 *
 * @param {string} text - The text the rendered node actually shows
 */
function expectNoControlBytes(text) {
  expect(text).not.toContain(ESC);
  expect(text).not.toContain(C1_CSI);
  expect(text).not.toContain(C1_OSC);
  // The same check in a shape a human can read in the failure message: the
  // escaped bytes are visible there instead of invisible control characters.
  expect(JSON.stringify(text)).not.toMatch(/\\u001b|\\u009b|\\u009d/);
  // No C0 control (but TAB and LF) and no DEL.
  expect(text).not.toMatch(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/);
}

const baseRows = [
  { key: 'image', step: 0, label: 'Image', values: ['nginx:1.27-alpine'] },
  { key: 'name', step: 1, label: 'Name', values: ['(auto-generated by Docker)'], origin: 'Docker will assign a name' },
  { key: 'ports', step: 2, label: 'Ports', values: ['8080→80/tcp'], origin: 'assigned by CDD' },
  { key: 'env', step: 3, label: 'Env', values: ['(none)'] },
];

describe('CreationSummary', () => {
  test('renders all row labels', () => {
    const { getByText } = render(
      <CreationSummary
        rows={baseRows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );
    expect(getByText('Review and confirm')).toBeTruthy();
    expect(getByText('Image')).toBeTruthy();
    expect(getByText('Name')).toBeTruthy();
    expect(getByText('Ports')).toBeTruthy();
    expect(getByText('Env')).toBeTruthy();
  });

  test('renders row values', () => {
    const { getByText } = render(
      <CreationSummary
        rows={baseRows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );
    expect(getByText('nginx:1.27-alpine')).toBeTruthy();
    expect(getByText('(auto-generated by Docker)')).toBeTruthy();
    expect(getByText('8080→80/tcp')).toBeTruthy();
  });

  test('renders origin text when present', () => {
    const { getByText } = render(
      <CreationSummary
        rows={baseRows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );
    expect(getByText(/\u2193 Docker will assign a name/)).toBeTruthy();
    expect(getByText(/\u2193 assigned by CDD/)).toBeTruthy();
  });

  test('does NOT render origin when absent', () => {
    const rows = [
      { key: 'image', step: 0, label: 'Image', values: ['nginx:1.27-alpine'] },
    ];
    const { queryByText } = render(
      <CreationSummary
        rows={rows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );
    expect(queryByText(/\u2193/)).toBeNull();
  });

  test('renders warnings with correct color', () => {
    const warnings = [
      { kind: 'image-pull', level: 'info', text: 'Image will be pulled.' },
      { kind: 'port-taken', level: 'warn', text: 'Port 8080 is in use.' },
    ];
    const { getByText } = render(
      <CreationSummary
        rows={baseRows}
        warnings={warnings}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );
    expect(getByText(/Image will be pulled/)).toBeTruthy();
    expect(getByText(/Port 8080 is in use/)).toBeTruthy();
  });

  test('does NOT render warnings when empty', () => {
    const { queryByText } = render(
      <CreationSummary
        rows={baseRows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );
    expect(queryByText('\u26A0')).toBeNull();
  });

  test('shows loading preview text when isLoadingPreview is true', () => {
    const { getByText } = render(
      <CreationSummary
        rows={baseRows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={true}
      />
    );
    expect(getByText(/Checking image/)).toBeTruthy();
  });

  test('hides loading preview text when isLoadingPreview is false', () => {
    const { queryByText } = render(
      <CreationSummary
        rows={baseRows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );
    expect(queryByText(/Checking image/)).toBeNull();
  });
});

describe('CreationSummary — rows CDD changed', () => {
  const renderRows = (rows, revealSecrets = false) =>
    render(
      <CreationSummary
        rows={rows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
        revealSecrets={revealSecrets}
      />
    );

  test('a changed row says so', () => {
    const { getByText } = renderRows([
      { key: 'env', step: 3, label: 'Env', values: ['POSTGRES_PASSWORD'], changed: true },
    ]);
    expect(getByText(/changed by CDD/)).toBeTruthy();
  });

  test('an untouched row does not', () => {
    const { queryByText } = renderRows([
      { key: 'env', step: 3, label: 'Env', values: ['POSTGRES_PASSWORD'] },
    ]);    expect(queryByText(/changed by CDD/)).toBeNull();
  });

  test('only the changed rows are marked', () => {
    const { getAllByText } = renderRows([
      { key: 'name', step: 1, label: 'Name', values: ['db-2'], changed: true },
      { key: 'env', step: 3, label: 'Env', values: ['A=1'] },
    ]);
    expect(getAllByText(/changed by CDD/)).toHaveLength(1);
  });

  test('a changed row keeps its origin line', () => {
    const { getByText } = renderRows([
      {
        key: 'ports',
        step: 2,
        label: 'Ports',
        values: ['8081→80/tcp'],
        origin: 'assigned by CDD',
        changed: true,
      },
    ]);
    expect(getByText(/↓ assigned by CDD/)).toBeTruthy();
    expect(getByText(/changed by CDD/)).toBeTruthy();
  });

  test('a changed env row still masks its secrets', () => {
    const { getByText } = renderRows([
      {
        key: 'env',
        step: 3,
        label: 'Env',
        values: ['POSTGRES_PASSWORD=•••••• [^R]'],
        changed: true,
      },
    ]);
    expect(getByText('POSTGRES_PASSWORD=•••••• [^R]')).toBeTruthy();
  });

  describe('empty secret values', () => {
    const emptyRow = [
      { key: 'env', step: 3, label: 'Env', values: ['POSTGRES_PASSWORD=(empty)'] },
    ];

    test('shows (empty) with no mask hint while secrets are hidden', () => {
      const { getByText, queryByText } = renderRows(emptyRow, false);
      expect(getByText('POSTGRES_PASSWORD=(empty)')).toBeTruthy();
      expect(queryByText(/\[\^R\]/)).toBeNull();
    });

    test('shows (empty) with no mask hint while secrets are revealed', () => {
      const { getByText, queryByText } = renderRows(emptyRow, true);
      expect(getByText('POSTGRES_PASSWORD=(empty)')).toBeTruthy();
      expect(queryByText(/\[\^R\]/)).toBeNull();
    });

    test('a filled secret still carries the hint, and reveals on demand', () => {
      const rows = [
        { key: 'env', step: 3, label: 'Env', values: ['POSTGRES_PASSWORD=hunter2'] },
      ];
      expect(renderRows(rows, false).getByText('POSTGRES_PASSWORD=•••••• [^R]')).toBeTruthy();
      expect(renderRows(rows, true).getByText('POSTGRES_PASSWORD=hunter2')).toBeTruthy();
    });
  });
});

describe('CreationSummary — terminal control sequences', () => {
  // The rows of the review screen can come from a container that was
  // inspected, so they hold text CDD did not write. Ink writes that text to
  // stdout verbatim, so a sequence in there would be executed by the
  // terminal. These tests are the regression: they must FAIL the moment the
  // `sanitizeTerminalText` call is removed from the component.

  const renderSummary = (rows, warnings = []) =>
    render(
      <CreationSummary
        rows={rows}
        warnings={warnings}
        focusedRow={0}
        isLoadingPreview={false}
      />
    );

  test('a value that carries a colour escape is shown without the control bytes', () => {
    const { container } = renderSummary([
      {
        key: 'image',
        step: 0,
        label: 'Image',
        values: [`nginx:${CSI}31mFAKE${CSI}0m`],
      },
    ]);
    const text = container.textContent;
    expect(text).toContain('nginx:FAKE');
    expectNoControlBytes(text);
  });

  test('a plain value is shown intact', () => {
    const { container } = renderSummary([
      { key: 'image', step: 0, label: 'Image', values: ['nginx:1.27-alpine'] },
    ]);
    expect(container.textContent).toContain('nginx:1.27-alpine');
  });

  test('a non-secret env value that carries an escape is shown without the control bytes', () => {
    const { container } = renderSummary([
      { key: 'env', step: 3, label: 'Env', values: [`DB_NAME=${CSI}31mapp`] },
    ]);
    const text = container.textContent;
    expect(text).toContain('DB_NAME=app');
    expectNoControlBytes(text);
  });

  test('a secret env value is masked and never reaches the screen', () => {
    const { container } = renderSummary([
      {
        key: 'env',
        step: 3,
        label: 'Env',
        values: [`POSTGRES_PASSWORD=hunter2${CSI}31mFAKE`],
      },
    ]);
    const text = container.textContent;
    expect(text).toContain('POSTGRES_PASSWORD=•••••• [^R]');
    expect(text).not.toContain('hunter2');
    expectNoControlBytes(text);
  });

  test('the origin line and the warning text are sanitised too', () => {
    const { container } = renderSummary(
      [
        {
          key: 'name',
          step: 1,
          label: 'Name',
          values: ['db'],
          origin: `Docker${CSI}31mFAKE`,
        },
      ],
      [{ kind: 'image-pull', level: 'info', text: `Image will be pulled.${CSI}31m` }]
    );
    const text = container.textContent;
    expect(text).toContain('DockerFAKE');
    expect(text).toContain('Image will be pulled.');
    expectNoControlBytes(text);
  });

  test('legitimate text is not mutiled', () => {
    // The sanitiser must not touch what is legitimate: accents, emoji and
    // the symbols Ink escapes itself all have to come out as they went in.
    const value = 'a & b < c > d — ñandú 🐳 café';
    const { container } = renderSummary([
      { key: 'image', step: 0, label: 'Image', values: [value] },
    ]);
    expect(container.textContent).toContain(value);
  });
});

describe('CreationSummary — the review of an env that carries a sequence', () => {
  // The env of a recreated container comes from its inspect, so it can carry
  // control sequences. The review must decide what to mask on the text it
  // shows: deciding on the raw text, the "=" of a sequence could pass for the
  // "=" of the variable and the secret would be shown in clear.
  test('the secret is masked, not shown', () => {
    const rows = buildCreationSummary(
      {
        imageName: 'postgres',
        containerName: '',
        portInput: '',
        envInput: `${ESC}]52;c;cGFzcw==\u0007POSTGRES_PASSWORD=hunter2`,
      },
      { rawImageInput: 'postgres', imageProfiles: {}, previewedPorts: null }
    );
    const { container } = render(
      <CreationSummary
        rows={rows}
        warnings={[]}
        focusedRow={0}
        isLoadingPreview={false}
        revealSecrets={false}
      />
    );
    const text = container.textContent;
    expect(text).not.toContain('hunter2');
    expect(text).toContain('\u2022');
    expectNoControlBytes(text);
  });
});
